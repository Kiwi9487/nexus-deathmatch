export function t(key, vars) {
  let str = (DICT[settings.lang] && DICT[settings.lang][key]) ?? DICT.en[key] ?? DICT.es[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v))
    }
  }
  return str
}

export function weaponName(id) {
  return t('weapon_' + id)
}

export function setLanguage(code) {
  if (!DICT[code] || settings.lang === code) return
  settings.lang = code
  saveSettings()
  applyLanguage()
  window.dispatchEvent(new CustomEvent('nexus-language-change', { detail: { code } }))
}

export function applyLanguage() {
  document.title = t('title')
  document.documentElement.lang = settings.lang
}
